package com.facetlauncher.app.data.local

import com.facetlauncher.app.data.model.ClockStackItem
import com.facetlauncher.app.data.model.Facet

internal fun FacetEntity.toFacet(clockStack: List<ClockStackItem> = emptyList()): Facet = Facet(
    id = id,
    name = name,
    position = position,
    clockPlacementOwn = clockPlacementOwn,
    clockAlignment = clockAlignment,
    clockZoneHeightDp = clockZoneHeightDp,
    clockStack = clockStack,
    landscapeClockAlignment = landscapeClockAlignment,
    landscapeClockZoneHeightDp = landscapeClockZoneHeightDp,
    appRowPosition = appRowPosition,
    landscapeAppRowPosition = landscapeAppRowPosition,
    landscapeAppListVerticalAlignment = landscapeAppListVerticalAlignment,
    landscapeAppListColumnAlignment = landscapeAppListColumnAlignment,
    allowLandscape = allowLandscape,
    appRowPresentation = appRowPresentation,
    listContentMode = listContentMode,
    appsToShowCount = appsToShowCount,
    appListVerticalAlignment = appListVerticalAlignment,
    appListLayout = appListLayout,
    appListColumnAlignment = appListColumnAlignment,
    appListGridColumns = appListGridColumns,
    appListGridDisplayMode = appListGridDisplayMode,
    appListShrinkToFit = appListShrinkToFit,
    dockDisplayMode = dockDisplayMode,
)

