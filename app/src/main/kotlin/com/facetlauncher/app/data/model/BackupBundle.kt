package com.facetlauncher.app.data.model

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/** Bumped whenever [BackupBundle]'s shape changes — [com.facetlauncher.app.domain.ImportBackupUseCase] rejects anything newer than it understands. */
const val CURRENT_BACKUP_VERSION = 3

/**
 * The full exported/imported settings snapshot for F14 Backup & Restore (PRD: "not limited to
 * favorites/profiles/dock — also includes widget hub state... icon/label customization... and
 * other user settings. Effectively a full settings snapshot, not a partial one.").
 *
 * Every enum field throughout this file is stored as its raw `.name` string (matching this
 * codebase's existing `Converters.kt`/`SettingsRepository` convention) rather than depending on
 * `data/model` enums being `@Serializable` themselves — [com.facetlauncher.app.domain.ExportBackupUseCase]/
 * [com.facetlauncher.app.domain.ImportBackupUseCase] convert to/from the real enum with the same
 * `runCatching { Enum.valueOf(it) }.getOrNull() ?: default` fallback used everywhere else in this
 * codebase, so an unrecognized value (an old export from before an enum constant was renamed)
 * degrades to that field's default instead of failing the whole import.
 *
 * Deliberately excluded from [BackupSettings] — not oversights, see each field's own reasoning:
 * - `activeFacetId`: a raw Room row id, meaningless after restore (facets get fresh
 *   autogenerated ids on import) — replaced by [BackupSettings.activeFacetIndex], an index into
 *   [BackupBundle.facets] that [com.facetlauncher.app.domain.ImportBackupUseCase] resolves to
 *   the newly-created facet's real id.
 * - `selectedCalendarIds`/`calendarColors`: keyed by `CalendarContract.Calendars` row ids, which
 *   are local-`ContentProvider` autoincrement values tied to which calendar accounts are synced
 *   on *this* device in *this* order — not portable to another device/reinstall, and silently
 *   matching the wrong calendar by coincidence is worse than just re-deriving them fresh.
 * - `allowLandscape`: a choice about this device (whether Home may rotate), not a layout preference.
 * - `calendarPermissionRequested`/`contactsPermissionRequested`/`bluetoothPermissionRequested`/
 *   `locationPermissionRequested`: track *this install's* runtime
 *   permission-request history, not a user preference — restoring `true` onto a device that was
 *   never actually asked would wrongly skip straight to the "go to App Info" fallback instead of
 *   firing the real system permission dialog.
 * - `onboardingCompleted`/`defaultsSeeded`/`coachMarksSeen`: this install's own first-run
 *   progress, not a user preference — restoring `true`/a populated set onto a fresh install would
 *   skip the first-run flow and its dock-seeding/coach-mark introductions entirely.
 */
@Serializable
data class BackupBundle(
    val backupVersion: Int = CURRENT_BACKUP_VERSION,
    val exportedAtEpochMillis: Long,
    val settings: BackupSettings,
    /** `@SerialName` keeps the JSON key `"profiles"` so backups exported before the Facet rename still import. */
    @SerialName("profiles")
    val facets: List<BackupFacet>,
    val dockApps: List<BackupAppEntry>,
    val defaultFavoriteApps: List<BackupAppEntry>,
    val widgetPlacements: List<BackupWidgetPlacement>,
    /**
     * The whole folder library (F-Folders) — every folder, regardless of where (if anywhere) it's
     * placed, in no particular order. Referenced by index (not id — a folder's own row id isn't
     * portable, same reasoning as [BackupSettings.activeFacetIndex]) from [dockFolderPlacements],
     * [defaultFavoriteFolderPlacements], and each [BackupFacet]'s own placement lists. Defaulted —
     * tolerant-reader discipline, see this file's own doc comment (a pre-Folders backup still
     * deserializes cleanly, with no folders to restore).
     */
    val folders: List<BackupFolder> = emptyList(),
    /** A folder placed in the launcher-wide default Dock — mirrors [dockApps] on the folder side. */
    val dockFolderPlacements: List<BackupFolderPlacement> = emptyList(),
    /** A folder placed in the launcher-wide default Favorites list — mirrors [defaultFavoriteApps] on the folder side. */
    val defaultFavoriteFolderPlacements: List<BackupFolderPlacement> = emptyList(),
)

