/** Mirrors every non-id field of `Facet` — its own row id isn't portable, same reasoning as [BackupSettings.activeFacetIndex]. */
@Serializable
data class BackupFacet(
    val name: String,
    val position: Int,
    val overrideClock: Boolean,
    val clockTemplateId: String,
    val clockFontOption: String,
    val clockColorOption: String,
    val use24HourTime: Boolean,
    val clockShowMeridiem: Boolean,
    /**
     * Added after the first release of this format; all defaulted, so an older backup restores to
     * today's defaults — no version bump. The hosted clock widget (its id and size) is left out:
     * an `AppWidgetHost` id is not portable, so that widget is re-added by hand like the Hub's.
     */
    val clockAccentColorOption: String = ClockColorOption.ACCENT_PRIMARY.name,
    val clockDateStyle: String = ClockDateStyle.FULL.name,
    val clockShowAlarm: Boolean = true,
    val clockShowBattery: Boolean = true,
    val clockShowWeather: Boolean = false,
    val clockWeatherIconStyle: String = WeatherIconStyle.COLORED.name,
    /** `null` in a backup from before placement was the facet's own: such a facet owned its placement exactly when it overrode the clock. */
    val clockPlacementOwn: Boolean? = null,
    val clockAlignment: String = ClockAlignment.LEFT.name,
    val clockZoneHeightDp: Float? = null,
    val clockScale: Float = 0.8f,
    val landscapeClockAlignment: String? = null,
    val landscapeClockZoneHeightDp: Float? = null,
    val landscapeClockScale: Float? = null,
    val landscapeAppListVerticalAlignment: String? = null,
    val appListVerticalAlignment: String = AppListVerticalAlignment.LAUNCHER_DEFAULT.name,
    val overrideApps: Boolean,
    val appRowPosition: String,
    val appRowPresentation: String,
    /** Defaulted — tolerant-reader discipline, see this file's own doc comment (a backup from before Home app-list layouts existed still deserializes cleanly, inheriting the launcher-wide layout). */
    val appListLayout: String = AppListLayout.LAUNCHER_DEFAULT.name,
    val appListColumnAlignment: String = AppListColumnAlignment.LAUNCHER_DEFAULT.name,
    /** Optional and additive, like [BackupSettings.landscapeAppRowPosition]. */
    val landscapeAppRowPosition: String? = null,
    val landscapeAppListColumnAlignment: String? = null,
    val appListGridColumns: String = AppListGridColumns.LAUNCHER_DEFAULT.name,
    val appListGridDisplayMode: String = AppListGridDisplayMode.LAUNCHER_DEFAULT.name,
    val listContentMode: String,
    val appsToShowCount: Int,
    val overridingFavorites: Boolean,
    /** Defaulted — tolerant-reader discipline, see this file's own doc comment (a v1 backup from before per-facet dock existed still deserializes cleanly, inheriting the launcher-wide dock). */
    val overrideDock: Boolean = false,
    val dockDisplayMode: String = DockDisplayMode.ICONS.name,
    /** This facet's own dock — only meaningful when [overrideDock], but exported unconditionally for simplicity; restoring is harmless either way since the launcher-wide dock governs whenever it isn't. */
    val dockApps: List<BackupAppEntry> = emptyList(),
    val overrideCalendar: Boolean,
    val showAllDayEvents: Boolean,
    val showCalendarIndicator: Boolean = true,
    val calendarItemsToShow: Int = CalendarDisplayOptions.MAX_ITEMS,
    /**
     * `null` means every calendar is implicitly selected — see [com.facetlauncher.app.data.local.FacetEntity.selectedCalendarIdsCsv]'s
     * own doc comment. A real JSON array here (not the Room column's comma-joined encoding),
     * matching how [BackupBundle] generally favors the more portable/readable shape. Defaulted
     * (not required) so an older backup missing this field still deserializes cleanly — see
     * [CURRENT_BACKUP_VERSION]'s own tolerant-reader discipline.
     */
    val selectedCalendarIds: List<String>? = null,
    /** This facet's own favorites — only meaningful when [overridingFavorites], but exported unconditionally for simplicity; restoring is harmless either way since the global default list governs whenever it isn't. */
    val favorites: List<BackupAppEntry>,
    /** A folder placed in this facet's own Dock — only meaningful when [overrideDock], mirrors [dockApps] on the folder side. Defaulted — tolerant-reader discipline. */
    val dockFolderPlacements: List<BackupFolderPlacement> = emptyList(),
    /** A folder placed in this facet's own Favorites list — only meaningful when [overridingFavorites], mirrors [favorites] on the folder side. Defaulted — tolerant-reader discipline. */
    val favoriteFolderPlacements: List<BackupFolderPlacement> = emptyList(),
)

/** A single app-list entry — dock, default favorites, or one facet's own favorites. */
@Serializable
data class BackupAppEntry(
    val packageName: String,
    val activityName: String,
    val position: Int,
    /** Raw `AppProfile.name` — defaulted so a backup exported before Work Profile support still imports cleanly (as `PERSONAL`, the only profile that existed then). */
    val profile: String = "PERSONAL",
)

/** One folder's identity + membership — a global, independent entity (F-Folders); see [BackupBundle.folders]' own doc for how it's referenced by index from every placement list. */
@Serializable
data class BackupFolder(
    val name: String,
    val apps: List<BackupAppEntry>,
)

/** A folder occupying one slot in some Dock/Favorites list. [folderIndex] indexes into [BackupBundle.folders] — not a raw id, same reasoning as [BackupSettings.activeFacetIndex]. */
@Serializable
data class BackupFolderPlacement(
    val folderIndex: Int,
    val position: Int,
)

/**
 * A Hub widget's *intent*, not its binding — see this file's top doc comment and the PRD's own
 * "Not yet addressed" note: an `AppWidgetHost`-issued `appWidgetId` isn't portable across installs
 * or devices, so this deliberately omits it. [com.facetlauncher.app.domain.ImportBackupUseCase]
 * never writes these to `widget_placements` directly — they're surfaced to the user as a guided
 * re-add queue (`ui/settings/backup/WidgetReimportScreen.kt`) that goes through the real
 * allocate/bind/configure flow again per widget, using [row]/[col]/[colSpan]/[rowSpan] as the
 * preferred placement.
 */
@Serializable
data class BackupWidgetPlacement(
    val providerPackageName: String,
    val providerClassName: String,
    val row: Int,
    val col: Int,
    val colSpan: Int,
    val rowSpan: Int,
    /** Raw `AppProfile.name` — defaulted so a backup exported before Work Profile support still imports cleanly (as `PERSONAL`). Only a hint for the guided re-add queue's initial bind attempt; re-adding always goes through a real bind, since a Work Profile widget's grant can't be restored from a backup file. */
    val profile: String = "PERSONAL",
    /** The widget's place in the landscape Hub's flow order, if it had one — defaulted so older backups import as "no order" (landscape then follows portrait's reading order). */
    val landscapeOrder: Int? = null,
)

/** A saved weather city in a backup file. */
@Serializable
data class BackupWeatherCity(val name: String, val latitude: Double, val longitude: Double, val timezone: String)
